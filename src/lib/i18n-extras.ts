export function extraLabel(locale: string, key: string, vars?: Record<string, string>) {
  let text = I18N_EXTRA[locale]?.[key] ?? I18N_EXTRA.en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) text = text.replaceAll(`{${k}}`, v);
  }
  return text;
}
