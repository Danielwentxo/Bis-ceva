export function createDemoArchive(): {
  concerts: Concert[];
  artists: Record<string, Artist>;
} {
  const artists: Record<string, Artist> = {};
  for (const a of DEMO_ARTISTS) artists[a.id] = { ...a };
  return {
    concerts: DEMO_CONCERTS.map((c) => ({ ...c, lineup: c.lineup.map((l) => ({ ...l })) })),
    artists,
  };
}
