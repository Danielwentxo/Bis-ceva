function artist(name: string, extras: Partial<Artist> = {}): Artist {
  return {
    id: extras.id ?? artistKey(name),
    name,
    logoUrl: extras.logoUrl ?? null,
    thumbUrl: extras.thumbUrl ?? null,
    genre: extras.genre ?? null,
    country: extras.country ?? null,
    bio: extras.bio ?? null,
  };
}

